import type { AwardCategory, Nominee, NomineeKind, ShameStat } from "./types";

type Draft = {
  slug: string;
  name: string;
  firstName?: string;
  lastName?: string;
  kind?: NomineeKind;
  club?: string;
  nation: string;
  nationCode?: string;
  position?: string;
  age?: string;
  nominations?: number;
  image?: string;
  portrait?: string;
  categories: AwardCategory[];
  charge: string;
  roast: string;
  why: string;
  relatedStorySlugs?: string[];
  extraStats?: ShameStat[];
};

function card(draft: Draft): Nominee {
  const stats: ShameStat[] = [
    ...(draft.age ? [{ label: "Age", value: draft.age }] : []),
    { label: "Nation", value: draft.nation },
    { label: "Nominations", value: String(draft.nominations ?? 1) },
    ...(draft.extraStats ?? []),
  ];

  return {
    slug: draft.slug,
    name: draft.name,
    firstName: draft.firstName,
    lastName: draft.lastName,
    kind: draft.kind ?? "player",
    club: draft.club,
    nation: draft.nation,
    nationCode: draft.nationCode,
    position: draft.position,
    age: draft.age,
    nominations: draft.nominations ?? 1,
    image: draft.image ?? `/portraits/${draft.slug}.jpg`,
    portrait: draft.portrait ?? `/portraits/${draft.slug}.jpg`,
    categories: draft.categories,
    charge: draft.charge,
    roast: draft.roast,
    stats,
    why: draft.why,
    relatedStorySlugs: draft.relatedStorySlugs ?? ["unveiling-2026"],
  };
}

